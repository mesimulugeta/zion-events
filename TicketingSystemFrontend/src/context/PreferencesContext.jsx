const PreferencesContext = createContext();
export const usePreferences = () => useContext(PreferencesContext);

const LEGACY_INLINE_VARS = [
  '--bg-color', '--text-color', '--card-bg', '--card-bg-alt',
  '--border-color', '--input-bg', '--navbar-bg', '--shadow',
];

export const PreferencesProvider = ({ children }) => {
  const [theme, setTheme]       = useState(() => localStorage.getItem('theme')    || 'LIGHT');
  const [language, setLanguage] = useState(() => localStorage.getItem('language') || 'ENGLISH');

  useEffect(() => {
    const root = document.documentElement;
    const body = document.body;

    LEGACY_INLINE_VARS.forEach(v => root.style.removeProperty(v));

    if (theme === 'DARK') {
      root.classList.add('dark-theme');
      body.classList.add('dark-theme');
    } else {
      root.classList.remove('dark-theme');
      body.classList.remove('dark-theme');
    }
    localStorage.setItem('theme', theme);
  }, [theme]);

  useEffect(() => {
    localStorage.setItem('language', language);
  }, [language]);

  const t = (key) => {
    const langMap = translations[language] || translations.ENGLISH;
    return langMap[key] ?? translations.ENGLISH[key] ?? key;
  };

  const updatePreferences = (newTheme, newLanguage) => {
    if (newTheme)    setTheme(newTheme);
    if (newLanguage) setLanguage(newLanguage);
  };

  // Called on logout — wipes back to defaults
  const resetPreferences = () => {
    setTheme('LIGHT');
    setLanguage('ENGLISH');
    localStorage.removeItem('theme');
    localStorage.removeItem('language');
  };

  return (
    <PreferencesContext.Provider value={{
      theme, language, setTheme, setLanguage,
      updatePreferences, resetPreferences, t
    }}>
      {children}
    </PreferencesContext.Provider>
  );
};